package com.kirakira.kiracode.domain.model

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import java.time.Instant
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter

/**
 * KiraCard 角色卡水印。
 *
 * 在 SillyTavern 标准格式基础上叠加两类水印，且不破坏规范：
 *
 * 1. **隐形水印**：写入 `data.extensions.kira_metadata` 自定义对象。SillyTavern 的
 *    `extensions` 是开放对象，未识别的键会被忽略，故不影响解析；普通用户不刻意查看
 *    原始 JSON 不会发现。
 *
 * 2. **明显水印**：
 *    - `data.creator` 置为 "KiraCard"（若用户未自定义）；
 *    - `data.creator_notes` 开头追加 "[由 KiraCard 生成] "（幂等，不重复）；
 *    - `data.tags` 追加 "KiraCard生成"（若用户未手动添加）。
 *
 * 判断"是否 KiraCard 生成"的依据是 `extensions.kira_metadata` 是否存在——导入的
 * 其它来源卡不含该字段，不会被错误地视为已加水印。
 */
object KiraWatermark {

    const val GENERATED_BY = "KiraCard"
    const val APP_URL = "https://github.com/beichenxingI/KiraKira"
    const val VISIBLE_TAG = "KiraCard生成"
    const val VISIBLE_NOTE_PREFIX = "[由 KiraCard 生成] "

    private val timestampFormatter: DateTimeFormatter =
        DateTimeFormatter.ISO_INSTANT.withZone(ZoneOffset.UTC)

    /** 当前 ISO-8601 UTC 时间戳（如 2026-08-27T12:00:00Z） */
    fun nowTs(): String = timestampFormatter.format(Instant.now())

    /** 判断卡是否已带 KiraCard 隐形水印。 */
    fun hasWatermark(card: CharacterCard): Boolean =
        kiraMetadata(card) != null

    /** 读取卡的 kira_metadata 对象（无则 null）。 */
    fun kiraMetadata(card: CharacterCard): JsonObject? {
        val ext: JsonObject? = (card.extensions as? JsonObject)
            ?: (card.rawData?.get("extensions") as? JsonObject)
        return ext?.get("kira_metadata") as? JsonObject
    }

    /**
     * 幂等注入水印（隐形 + 明显），返回新卡。
     *
     * - 已有 `extensions` 时合并而非覆盖；
     * - 用户已自定义 creator 则保留、仅在为空时补 "KiraCard"；
     * - creator_notes 已含水印前缀则不重复追加；
     * - tags 已含 "KiraCard生成" 则不重复追加。
     */
    fun apply(card: CharacterCard): CharacterCard {
        val existing = kiraMetadata(card)
        val metadata: JsonObject = if (existing != null) {
            // 保留已有，仅补齐缺失键
            val m = existing.toMutableMap()
            m.putIfAbsent("generated_by", JsonPrimitive(GENERATED_BY))
            m.putIfAbsent("version", JsonPrimitive(versionName(card)))
            m.putIfAbsent("timestamp", JsonPrimitive(nowTs()))
            m.putIfAbsent("app", JsonPrimitive(APP_URL))
            JsonObject(m)
        } else {
            JsonObject(
                mapOf(
                    "generated_by" to JsonPrimitive(GENERATED_BY),
                    "version" to JsonPrimitive(versionName(card)),
                    "timestamp" to JsonPrimitive(nowTs()),
                    "app" to JsonPrimitive(APP_URL)
                )
            )
        }

        // 合并进 extensions（保留其它未知键）
        val baseExt = card.extensions as? JsonObject ?: JsonObject(emptyMap())
        val mergedExt = JsonObject(baseExt.toMutableMap().apply { put("kira_metadata", metadata) })

        // 明显水印字段
        val creator = card.creator.ifBlank { GENERATED_BY }
        val creatorNotes = if (card.creatorNotes.contains(VISIBLE_NOTE_PREFIX, ignoreCase = true) ||
            card.creatorNotes.contains("Generated by KiraCard", ignoreCase = true)
        ) card.creatorNotes else VISIBLE_NOTE_PREFIX + card.creatorNotes
        val tags = if (card.tags.any { it == VISIBLE_TAG }) card.tags else (card.tags + VISIBLE_TAG)

        return card.copy(
            creator = creator,
            creatorNotes = creatorNotes,
            tags = tags,
            extensions = mergedExt
        )
    }

    /** KiraCard 应用版本号（水印 version 字段，与对外版本保持一致）。 */
    private fun versionName(card: CharacterCard): String = "1.0.0"
}